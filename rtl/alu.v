// Project 2: AI-Assisted RTL Verification & Bug Diagnosis
//============================================================
`timescale 1ns/1ps
module alu (
    input  wire [3:0] A,
    input  wire [3:0] B,
    input  wire [1:0] OP,

    output reg  [3:0] RESULT,
    output reg        CARRY
);

    //========================================================
    // ALU OPERATIONS
    //
    // OP = 00 : ADD
    // OP = 01 : AND
    // OP = 10 : OR
    // OP = 11 : XOR
    //========================================================

    always @(*) begin

        // Default values
        RESULT = 4'b0000;
        CARRY  = 1'b0;

        case (OP)

            // ------------------------------------------------
            // ADD
            // ------------------------------------------------
            2'b00: begin

                {CARRY, RESULT} = A + B;

            end


            // ------------------------------------------------
            // AND
            // ------------------------------------------------
            2'b01: begin

                RESULT = A & B;
                CARRY  = 1'b0;

            end


            // ------------------------------------------------
            // OR
            // ------------------------------------------------
            2'b10: begin

                RESULT = A | B;
                CARRY  = 1'b0;

            end


            // ------------------------------------------------
            // XOR
            // ------------------------------------------------
            2'b11: begin

                RESULT = A ^ B;
                CARRY  = 1'b0;

            end


            // ------------------------------------------------
            // DEFAULT
            // ------------------------------------------------
            default: begin

                RESULT = 4'b0000;
                CARRY  = 1'b0;

            end

        endcase

    end

endmodule